#!/usr/bin/env node
/**
 * Bake Netlify deploy identity into a module Functions can require at runtime.
 *
 * On this site, Functions do not receive automatic CONTEXT / BRANCH / DEPLOY_URL
 * (only URL/SITE_URL → production). Those vars ARE available at build time, so
 * we snapshot them here before the Functions bundle is packaged.
 *
 * Never add secret env vars here (auth tokens, session secrets, API keys,
 * personal phone numbers). The baked file is part of the Functions bundle.
 *
 * The only extra field is the sanitized boolean
 * STRIPE_PRODUCTION_CUSTOMER_PAYMENTS_ENABLED. It is true solely when the
 * build env string is exactly "true". Any other value, including absence,
 * is baked as false. The raw string is never written.
 */
'use strict';

const fs = require('fs');
const path = require('path');

const OUT = path.join(__dirname, '..', 'netlify', 'lib', 'deploy-runtime-env.generated.js');

const KEYS = [
  'CONTEXT',
  'BRANCH',
  'URL',
  'DEPLOY_URL',
  'DEPLOY_PRIME_URL',
  'DEPLOY_ID',
  'REVIEW_ID',
  'SITE_NAME',
];

function customerPaymentsBakedFlag(env = process.env) {
  return String((env && env.STRIPE_PRODUCTION_CUSTOMER_PAYMENTS_ENABLED) || '') === 'true';
}

function buildDeployRuntimeSnapshot(env = process.env) {
  const payload = {};
  for (const key of KEYS) {
    payload[key] = String((env && env[key]) || '').trim();
  }
  payload.STRIPE_PRODUCTION_CUSTOMER_PAYMENTS_ENABLED = customerPaymentsBakedFlag(env);
  return payload;
}

function renderDeployRuntimeModule(payload) {
  return `'use strict';
// AUTO-GENERATED by scripts/generate-deploy-runtime-env.js — do not edit.
// Build-time snapshot of Netlify deploy identity plus one sanitized boolean.
// STRIPE_PRODUCTION_CUSTOMER_PAYMENTS_ENABLED is true only when the build
// env string was exactly "true". No key or secret is written here.
module.exports = ${JSON.stringify(payload, null, 2)};
`;
}

function main() {
  const payload = buildDeployRuntimeSnapshot(process.env);
  const source = renderDeployRuntimeModule(payload);
  const out = process.env.DEPLOY_RUNTIME_ENV_OUT
    ? path.resolve(process.env.DEPLOY_RUNTIME_ENV_OUT)
    : OUT;
  fs.mkdirSync(path.dirname(out), { recursive: true });
  fs.writeFileSync(out, source, 'utf8');
  return { payload, out };
}

if (require.main === module) {
  const { payload } = main();
  const ctx = payload.CONTEXT || '(empty)';
  const deployHost = (() => {
    try {
      return payload.DEPLOY_URL ? new URL(payload.DEPLOY_URL).hostname : '(none)';
    } catch {
      return '(invalid)';
    }
  })();
  console.log(`[generate-deploy-runtime-env] CONTEXT=${ctx} BRANCH=${payload.BRANCH || '(empty)'} DEPLOY_HOST=${deployHost} customerPayments=${payload.STRIPE_PRODUCTION_CUSTOMER_PAYMENTS_ENABLED === true}`);
}

module.exports = {
  KEYS,
  customerPaymentsBakedFlag,
  buildDeployRuntimeSnapshot,
  renderDeployRuntimeModule,
};
